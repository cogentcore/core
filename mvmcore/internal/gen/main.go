// Command gen generates the mvm symbols of packages, one file per package,
// in the form of the basesymbols and coresymbols packages: a loader
// registered with register that adds the values of the exported names of
// the package, and registers its generic functions as mvm generic shims,
// whose source mvm interprets.
//
// Usage: go run cogentcore.org/core/mvmcore/internal/gen -pkg <name> <import-path>...
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/printer"
	"go/token"
	"go/types"
	"log"
	"os"
	"slices"
	"strings"

	"golang.org/x/tools/go/packages"
)

// pkgName is the package name of the generated files.
var pkgName = flag.String("pkg", "coresymbols", "package name of the generated files")

func main() {
	flag.Parse()
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo}
	pkgs, err := packages.Load(cfg, flag.Args()...)
	if err != nil {
		log.Fatal(err)
	}
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			log.Fatal(pkg.Errors[0])
		}
		src, err := generate(pkg)
		if err != nil {
			log.Fatalf("%s: %v", pkg.PkgPath, err)
		}
		name := "gen_" + strings.NewReplacer("/", "_", ".", "_").Replace(pkg.PkgPath) + ".go"
		if err := os.WriteFile(name, src, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

// generate returns the symbols file of pkg.
func generate(pkg *packages.Package) ([]byte, error) {
	scope := pkg.Types.Scope()
	alias := "p_" + strings.NewReplacer("/", "_", ".", "_", "-", "_").Replace(pkg.PkgPath)

	// The values of the exported names, and the generic functions and the
	// constraints, which are shim source.
	var values []string
	var generics []string
	constraints := map[string]bool{}
	for _, name := range scope.Names() {
		obj := scope.Lookup(name)
		if !obj.Exported() {
			continue
		}
		q := alias + "." + name
		switch obj := obj.(type) {
		case *types.Func:
			if obj.Type().(*types.Signature).TypeParams().Len() > 0 {
				generics = append(generics, name)
				continue
			}
			values = append(values, fmt.Sprintf("%q: reflect.ValueOf(%s),", name, q))
		case *types.Var:
			values = append(values, fmt.Sprintf("%q: reflect.ValueOf(&%s),", name, q))
		case *types.Const:
			values = append(values, fmt.Sprintf("%q: reflect.ValueOf(%s),", name, constExpr(obj, q)))
		case *types.TypeName:
			if obj.IsAlias() {
				if _, ok := obj.Type().(*types.Basic); ok {
					continue
				}
			}
			if named, ok := obj.Type().(*types.Named); ok && named.TypeParams().Len() > 0 {
				continue // generic types are not supported
			}
			if iface, ok := obj.Type().Underlying().(*types.Interface); ok && !iface.IsMethodSet() {
				constraints[name] = true
				continue
			}
			values = append(values, fmt.Sprintf("%q: reflect.ValueOf((*%s)(nil)),", name, q))
		}
	}

	shim, refs, err := shimSource(pkg, generics, constraints)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", pkg.PkgPath, *pkgName)
	if len(values) > 0 {
		fmt.Fprintf(&b, "\t%s %q\n", alias, pkg.PkgPath)
	}
	b.WriteString("\t\"reflect\"\n")
	if shim != "" {
		b.WriteString("\t\"github.com/cogentcore/mvm/goparser\"\n")
	}
	b.WriteString(")\n\nvar _ = register(func() {\n")
	if shim != "" {
		fmt.Fprintf(&b, "goparser.RegisterGenericShim(%q, %s, %#v)\n", pkg.PkgPath, backquote(shim), refs)
	}
	fmt.Fprintf(&b, "add(map[string]map[string]reflect.Value{\n%q: {\n", pkg.PkgPath)
	for _, v := range values {
		b.WriteString(v + "\n")
	}
	b.WriteString("},\n})\n})\n")
	out := b.String()
	return format.Source([]byte(out))
}

// constExpr returns the expression of the constant obj, named by q: q,
// converted to uint64 if it is an untyped integer too large for an int.
func constExpr(obj *types.Const, q string) string {
	if b, ok := obj.Type().(*types.Basic); ok && b.Info()&types.IsUntyped != 0 && obj.Val().Kind() == constant.Int {
		if _, exact := constant.Int64Val(obj.Val()); !exact {
			return "uint64(" + q + ")"
		}
	}
	return q
}

// backquote returns s as a Go raw string literal, or a quoted string if it
// has a backquote.
func backquote(s string) string {
	if strings.Contains(s, "`") {
		return fmt.Sprintf("%q", s)
	}
	return "`" + s + "`"
}

// shimSource returns the source of the shim of the generic functions of pkg
// named generics, with the declarations of the constraints that they use,
// and the names of the package that the source refers to, which the shim
// gets from the values of the package. A generic function that refers to an
// unexported name of the package is left out, as it could not be resolved.
func shimSource(pkg *packages.Package, generics []string, constraints map[string]bool) (string, []string, error) {
	if len(generics) == 0 {
		return "", nil, nil
	}
	decls := map[string]ast.Decl{}
	for _, f := range pkg.Syntax {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && slices.Contains(generics, d.Name.Name) {
					decls[d.Name.Name] = d
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					if ts, ok := s.(*ast.TypeSpec); ok && constraints[ts.Name.Name] {
						decls[ts.Name.Name] = &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{ts}}
					}
				}
			}
		}
	}

	// Find what each declaration refers to: names of the package and
	// imported packages.
	scope := pkg.Types.Scope()
	type uses struct {
		names   map[string]bool
		imports map[string]string // import path by package name
		bad     bool
	}
	use := func(d ast.Decl) uses {
		u := uses{names: map[string]bool{}, imports: map[string]string{}}
		ast.Inspect(d, func(n ast.Node) bool {
			id, ok := n.(*ast.Ident)
			if !ok {
				return true
			}
			obj := pkg.TypesInfo.Uses[id]
			switch obj := obj.(type) {
			case *types.PkgName:
				u.imports[id.Name] = obj.Imported().Path()
			case nil:
			default:
				if obj.Pkg() == pkg.Types && obj.Parent() == scope {
					if !obj.Exported() {
						u.bad = true
					}
					u.names[obj.Name()] = true
				}
			}
			return true
		})
		return u
	}

	// The generic functions and constraints, without those that refer to
	// unexported names, and the names and imports of those kept.
	var srcs []string
	refs := map[string]bool{}
	imports := map[string]string{}
	var names []string
	for name := range decls {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		d := decls[name]
		u := use(d)
		if u.bad {
			log.Printf("%s: leaving out %s, which uses unexported names", pkg.PkgPath, name)
			continue
		}
		var b bytes.Buffer
		if fd, ok := d.(*ast.FuncDecl); ok {
			fd.Doc = nil
		}
		if err := printer.Fprint(&b, pkg.Fset, d); err != nil {
			return "", nil, err
		}
		srcs = append(srcs, stripComments(b.String()))
		for n := range u.names {
			if n != name && decls[n] == nil {
				refs[n] = true
			}
		}
		for k, v := range u.imports {
			imports[k] = v
		}
	}
	if len(srcs) == 0 {
		return "", nil, nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\n", pkg.Name)
	var inames []string
	for k := range imports {
		inames = append(inames, k)
	}
	slices.Sort(inames)
	for _, k := range inames {
		fmt.Fprintf(&b, "import %s %q\n", k, imports[k])
	}
	for _, s := range srcs {
		b.WriteString("\n" + s + "\n")
	}
	var rl []string
	for k := range refs {
		rl = append(rl, k)
	}
	slices.Sort(rl)
	return b.String(), rl, nil
}

// stripComments removes the line comments of src that are on lines of
// their own.
func stripComments(src string) string {
	var out []string
	for _, l := range strings.Split(src, "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "//") {
			continue
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}
