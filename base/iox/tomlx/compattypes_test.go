// This file defines the types used by the compatibility tests, which
// read files written by the pelletier/go-toml/v2 based version of
// tomlx that Cogent Core used before. The same types (and compatValue)
// were used to generate testdata/pelletier.toml with that version,
// so they must not be changed without regenerating it.

// compatEnum is an enum type like those generated by enumgen,
// which encode as their string names.
type compatEnum int32

const (
	enumNone compatEnum = iota
	enumApple
	enumBanana
)

var compatEnumNames = []string{"None", "Apple", "Banana"}

func (e compatEnum) String() string { return compatEnumNames[e] }

func (e compatEnum) MarshalText() ([]byte, error) { return []byte(e.String()), nil }

func (e *compatEnum) UnmarshalText(text []byte) error {
	for i, n := range compatEnumNames {
		if n == string(text) {
			*e = compatEnum(i)
			return nil
		}
	}
	return errors.New("invalid compatEnum: " + string(text))
}

// compatChord is a named string type, like key.Chord.
type compatChord string

// compatInner is a nested struct.
type compatInner struct {
	Name  string
	Value float32
	Dur   time.Duration
	Tags  []string
	Color color.RGBA
}

// CompatEmbed is embedded in compatData.
type CompatEmbed struct {
	EmbedName string
	EmbedInt  int
}

// compatOption is like option.Option.
type compatOption[T any] struct {
	Value T
	Valid bool
}

// compatMapsItem is like keymap.MapsItem.
type compatMapsItem struct {
	Name string
	Desc string
	Map  map[compatChord]compatEnum
}

// compatList is like keylist.List.
type compatList[K comparable, V any] struct {
	Values  []V
	Keys    []K
	indexes map[K]int
}

// compatData has fields of representative types used in settings
// and configuration files.
type compatData struct {
	CompatEmbed

	String     string
	Quoted     string
	Multiline  string
	Unicode    string
	Bool       bool
	Int        int
	Int8       int8
	Int64      int64
	Uint8      uint8
	Uint32     uint32
	Float32    float32
	Float64    float64
	WholeFloat float32
	Dur        time.Duration
	Durs       []time.Duration
	Time       time.Time
	Enum       compatEnum
	Enums      []compatEnum
	Chord      compatChord
	Color      color.RGBA
	Floats     [4]float32
	Ints       []int
	Strings    []string
	EmptySlice []string
	NilSlice   []string
	Bytes      []byte

	Inner     compatInner
	InnerPtr  *compatInner
	NilPtr    *compatInner
	Inners    []compatInner
	InnerPtrs []*compatInner

	StringMap   map[string]string
	IntMap      map[int]string
	Int64Map    map[int64]float64
	UintMap     map[uint8]bool
	EnumMap     map[compatEnum]string
	EnumPtrMap  map[compatEnum]*compatInner
	ChordMap    map[compatChord]compatEnum
	StructMap   map[string]compatInner
	IntBoolMap  map[int]bool
	EmptyMap    map[string]int
	NilMap      map[string]int
	AnyMap      map[string]any
	NestedMap   map[string]map[int]string
	Option      compatOption[[]compatMapsItem]
	List        compatList[string, *compatInner]
	Ignored     string `toml:"-"`
	Renamed     string `toml:"renamed_field"`
	unexported  int
	AnyValue    any
	SliceOfMaps []map[string]int
}

// compatValue returns the value used to generate testdata/pelletier.toml.
func compatValue() *compatData {
	inner := func(name string, v float32) compatInner {
		return compatInner{Name: name, Value: v, Dur: 1500 * time.Millisecond, Tags: []string{"x", "y"}, Color: color.RGBA{10, 20, 30, 255}}
	}
	ip := inner("ptr", 2.5)
	ia, ib := inner("a", 1), inner("b", 0.1)
	return &compatData{
		CompatEmbed: CompatEmbed{EmbedName: "embedded", EmbedInt: 7},
		String:      "hello",
		Quoted:      `it's "quoted" \ back`,
		Multiline:   "line one\nline two\ttab",
		Unicode:     "héllo 世界",
		Bool:        true,
		Int:         -42,
		Int8:        -8,
		Int64:       1 << 40,
		Uint8:       200,
		Uint32:      4000000000,
		Float32:     3.14,
		Float64:     2.718281828459045,
		WholeFloat:  100,
		Dur:         5 * time.Second,
		Durs:        []time.Duration{time.Millisecond, 250 * time.Millisecond, 2 * time.Minute},
		Time:        time.Date(2024, 3, 15, 10, 30, 0, 0, time.UTC),
		Enum:        enumBanana,
		Enums:       []compatEnum{enumApple, enumBanana},
		Chord:       "Control+S",
		Color:       color.RGBA{66, 133, 244, 255},
		Floats:      [4]float32{0.25, 0.25, 0.5, 0},
		Ints:        []int{1, 2, 3},
		Strings:     []string{"a", "b c", "d'e"},
		EmptySlice:  []string{},
		Bytes:       []byte("bytes"),
		Inner:       inner("inner", 0.5),
		InnerPtr:    &ip,
		Inners:      []compatInner{ia, ib},
		InnerPtrs:   []*compatInner{&ia},
		StringMap:   map[string]string{"k1": "v1", "key two": "v2", "a.b": "dotted"},
		IntMap:      map[int]string{1: "one", 20: "twenty", -3: "minus three"},
		Int64Map:    map[int64]float64{100: 1.5},
		UintMap:     map[uint8]bool{7: true},
		EnumMap:     map[compatEnum]string{enumApple: "red", enumBanana: "yellow"},
		EnumPtrMap:  map[compatEnum]*compatInner{enumApple: &ip},
		ChordMap:    map[compatChord]compatEnum{"Control+A": enumApple, "Shift+B": enumBanana},
		StructMap:   map[string]compatInner{"first": ia},
		IntBoolMap:  map[int]bool{0: true, 1: false},
		EmptyMap:    map[string]int{},
		AnyMap:      map[string]any{"Int": int64(3), "Float": 1.5, "Str": "s", "Sub": map[string]any{"X": int64(1)}},
		NestedMap:   map[string]map[int]string{"outer": {1: "a", 2: "b"}},
		Option: compatOption[[]compatMapsItem]{Valid: true, Value: []compatMapsItem{
			{Name: "MacStandard", Desc: "Standard Mac", Map: map[compatChord]compatEnum{"Command+S": enumApple, "Control+X": enumBanana}},
			{Name: "Empty", Desc: "no map"},
		}},
		List:        compatList[string, *compatInner]{Keys: []string{"srv1"}, Values: []*compatInner{&ib}},
		Ignored:     "",
		Renamed:     "renamed",
		AnyValue:    "any string",
		SliceOfMaps: []map[string]int{{"a": 1}, {"b": 2}},
	}
}
