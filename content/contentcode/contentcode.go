// generated names; the prefix keeps them apart from the app's names.
const (
	prefix    = "contentCode"
	parentVar = prefix + "Parent"
	outVar    = prefix + "Out"
)

// version is the version of the generated code. Changing it changes the hash
// of all output, so that it is generated again.
const version = "2"

// header is the first line of the output file.
const header = "// Code generated by \"contentcode\"; DO NOT EDIT.\n"

// hashPrefix starts the line of the output file that records its hash.
const hashPrefix = "// contentcode hash: "

// contentImport is the import path of the content package.
const contentImport = "cogentcore.org/core/content"

// Config is the configuration of [Generate].
type Config struct {

	// Dir is the directory of the package (default: the current directory).
	// Content and Output are relative to it.
	Dir string

	// Content is the directory of the markdown content.
	Content string

	// Output is the output Go file, in the package.
	Output string

	// Tags are build tags for type checking.
	Tags string

	// Imports are extra packages that code can use: path or name=path.
	Imports []string

	// GoalRecord is whether Goal math mode records its variables in
	// tensorfs and lists tensorfs to the output, as the Goal interpreter
	// of Lab's mvmlab does. It is true by default; set it to false for
	// sites whose interpreter does not (such as plain goal).
	GoalRecord bool

	// Force generates the output even if it is up to date.
	Force bool
}

type importFlags []string

func (f *importFlags) String() string     { return strings.Join(*f, ",") }
func (f *importFlags) Set(s string) error { *f = append(*f, s); return nil }

// ParseArgs returns the configuration given by the arguments of the
// contentcode command.
func ParseArgs(name string, args []string) (*Config, error) {
	c := &Config{}
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.StringVar(&c.Content, "content", "content", "directory of the markdown content")
	fs.StringVar(&c.Output, "o", "contentcode_gen.go", "output Go file, in the current package")
	fs.StringVar(&c.Tags, "tags", "", "build tags for type checking")
	fs.Var((*importFlags)(&c.Imports), "import", "extra package that code can use: path or name=path (repeatable)")
	fs.BoolVar(&c.GoalRecord, "goal-record", true, "record the variables of Goal math mode in tensorfs and list tensorfs to the output, as Lab's mvmlab interpreter does")
	fs.BoolVar(&c.Force, "force", false, "generate even if the output is up to date")
	if err := fs.Parse(args); err != nil {
		return nil, err
	}
	if fs.NArg() > 0 {
		return nil, fmt.Errorf("unexpected arguments: %v", fs.Args())
	}
	return c, nil
}

// App returns the configuration for the package in dir if it is a content
// app: a main package that imports the content package and embeds (or has)
// a directory with markdown files. If a go:generate directive of the
// package runs contentcode, App uses its arguments. It returns nil if the
// package is not a content app.
func App(dir string) (*Config, error) {
	// a main package that imports content
	pkg, err := build.ImportDir(dir, 0)
	if err != nil {
		var noGo *build.NoGoError
		if errors.As(err, &noGo) {
			return nil, nil
		}
		return nil, err
	}
	if pkg.Name != "main" || !slices.Contains(pkg.Imports, contentImport) {
		return nil, nil
	}

	// a go:generate directive gives the arguments
	c, err := generateDirective(dir, pkg.GoFiles)
	if err != nil || c != nil {
		return c, err
	}
	c, _ = ParseArgs("contentcode", nil)
	c.Dir = dir

	// the embedded directory of markdown files, or content
	c.Content = ""
	for _, p := range pkg.EmbedPatterns {
		p = strings.TrimPrefix(p, "all:")
		if hasMarkdown(filepath.Join(dir, p)) {
			c.Content = p
			break
		}
	}
	if c.Content == "" && hasMarkdown(filepath.Join(dir, "content")) {
		c.Content = "content"
	}
	if c.Content == "" {
		return nil, nil
	}
	return c, nil
}

// generateDirective returns the configuration given by a go:generate
// directive that runs contentcode in one of the given files of dir.
func generateDirective(dir string, files []string) (*Config, error) {
	for _, f := range files {
		b, err := os.ReadFile(filepath.Join(dir, f))
		if err != nil {
			return nil, err
		}
		for _, l := range strings.Split(string(b), "\n") {
			args, ok := strings.CutPrefix(strings.TrimSpace(l), "//go:generate ")
			if !ok {
				continue
			}
			fields := strings.Fields(args)
			i := slices.IndexFunc(fields, func(s string) bool {
				return s == "contentcode" || strings.HasSuffix(s, "/contentcode")
			})
			if i < 0 {
				continue
			}
			c, err := ParseArgs("contentcode", fields[i+1:])
			if err != nil {
				return nil, fmt.Errorf("%s: go:generate contentcode: %w", f, err)
			}
			c.Dir = dir
			return c, nil
		}
	}
	return nil, nil
}

// hasMarkdown returns whether dir is a directory that has markdown files.
func hasMarkdown(dir string) bool {
	found := false
	filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return fs.SkipAll
		}
		if !d.IsDir() && filepath.Ext(path) == ".md" {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	return found
}

// Generate writes the output file of the code blocks of the content, unless
// it is up to date. It returns whether it wrote the file. If the content has
// no code blocks, it removes a previously generated output file instead.
func Generate(c *Config) (bool, error) {
	dir := c.Dir
	if dir == "" {
		dir = "."
	}
	output := filepath.Join(dir, c.Output)
	importPaths := map[string]string{} // package name -> path
	for _, p := range defaultImports {
		importPaths[pathName(p)] = p
	}
	for _, e := range c.Imports {
		name, path, ok := strings.Cut(e, "=")
		if !ok {
			name, path = pathName(e), e
		}
		importPaths[name] = path
	}
	goalPaths := map[string]string{} // for Goal code
	for _, p := range goalImports {
		goalPaths[pathName(p)] = p
	}
	for _, p := range defaultImports {
		goalPaths[pathName(p)] = p
	}
	for _, e := range c.Imports {
		name, path, ok := strings.Cut(e, "=")
		if !ok {
			name, path = pathName(e), e
		}
		goalPaths[name] = path
	}

	// the blocks and the hash of what the output is generated from
	blocks, err := readBlocks(dir, c.Content)
	if err != nil {
		return false, err
	}
	pages, err := readGoalPages(dir, c.Content)
	if err != nil {
		return false, err
	}
	old, _ := os.ReadFile(output)
	if len(blocks) == 0 && len(pages) == 0 {
		if bytes.HasPrefix(old, []byte(header)) {
			return true, os.Remove(output)
		}
		return false, nil
	}
	hash, err := c.hash(dir, blocks, pages)
	if err != nil {
		return false, err
	}
	if !c.Force && bytes.Contains(old, []byte(hashPrefix+hash+"\n")) {
		return false, nil
	}

	pkgName, err := packageName(dir, c.Tags)
	if err != nil {
		return false, err
	}
	for i, b := range blocks {
		b.name = fmt.Sprintf("%s%d", prefix, i)
		if err := b.generate(importPaths); err != nil {
			b.err = err.Error()
		}
	}
	if err := transpileGoal(dir, pages, c.Tags, c.GoalRecord); err != nil {
		if !errors.Is(err, errNoLab) {
			return false, err
		}
		// the Go code blocks are still compiled
		fmt.Fprintf(os.Stderr, "%s:%d: Goal code blocks are not compiled into the app, since compiling Goal code needs Cogent Lab, which the module of the app does not require; to compile them, run: go get cogentcore.org/lab (until then, they run in the Goal interpreter, if the app has one)\n", displayPath(dir, pages[0].file), pages[0].blocks[0].line)
		pages = nil
	}
	for i, pg := range pages {
		pg.name = fmt.Sprintf("%s%d", goalPrefix, i)
		pg.prepare(goalPaths, c.GoalRecord)
	}
	src, err := typeCheckBlocks(dir, output, pkgName, hash, c.Tags, blocks, pages, goalPaths, c.GoalRecord)
	if err != nil {
		// keep the previous output, not a partial one
		if old != nil {
			os.WriteFile(output, old, 0666)
		} else {
			os.Remove(output)
		}
		return false, err
	}
	if err := os.WriteFile(output, src, 0666); err != nil {
		return false, err
	}
	n := 0
	for _, b := range blocks {
		if b.err == "" {
			n++
			continue
		}
		// the errors of the block, at their place in the markdown file
		file := displayPath(dir, b.file)
		if len(b.errs) == 0 {
			fmt.Fprintf(os.Stderr, "%s:%d: %s\n", file, b.line, b.err)
		}
		for _, e := range b.errs {
			if e.col > 0 {
				fmt.Fprintf(os.Stderr, "%s:%d:%d: %s\n", file, e.line, e.col, e.msg)
			} else {
				fmt.Fprintf(os.Stderr, "%s:%d: %s\n", file, e.line, e.msg)
			}
		}
	}
	if n < len(blocks) {
		fmt.Fprintf(os.Stderr, "contentcode: compiled %d of %d code blocks into %s; the others, with the errors above, run in the interpreter instead, if the app has one\n", n, len(blocks), output)
	} else if len(blocks) > 0 {
		fmt.Fprintf(os.Stderr, "contentcode: compiled %d of %d code blocks into %s\n", n, len(blocks), output)
	}
	if len(pages) > 0 {
		nb, ng := 0, 0
		for _, pg := range pages {
			ng += len(pg.blocks)
			nb += pg.n
			if pg.n < len(pg.blocks) {
				b := pg.blocks[pg.n]
				fmt.Fprintf(os.Stderr, "%s:%d: %s\ncontentcode: this Goal code block and the %d after it on its page are not compiled into the app; they run in the Goal interpreter instead, if the app has one\n", displayPath(dir, pg.file), b.line, b.err, len(pg.blocks)-pg.n-1)
			}
		}
		fmt.Fprintf(os.Stderr, "contentcode: compiled %d of %d Goal code blocks (%d pages) into %s\n", nb, ng, len(pages), output)
	}
	return true, nil
}

// hash returns the hash of what the output is generated from: the version,
// the options, the go.mod file of the package and the code blocks.
func (c *Config) hash(dir string, blocks []*block, pages []*goalPage) (string, error) {
	h := sha256.New()
	fmt.Fprintf(h, "version %s\ntags %s\nimports %q\n", version, c.Tags, c.Imports)
	if len(pages) > 0 {
		fmt.Fprintf(h, "goal-record %v\n", c.GoalRecord)
	}
	gomod, err := goModFile(dir)
	if err != nil {
		return "", err
	}
	if gomod != "" {
		b, err := os.ReadFile(gomod)
		if err != nil {
			return "", err
		}
		h.Write(b)
	}
	for _, b := range blocks {
		fmt.Fprintf(h, "\n%s #%d %d\n%s", b.file, b.index, len(b.src), b.src)
	}
	for _, pg := range pages {
		for _, b := range pg.blocks {
			fmt.Fprintf(h, "\nGoal %s #%d %d\n%s", pg.file, b.index, len(b.src), b.src)
		}
	}
	return hex.EncodeToString(h.Sum(nil))[:32], nil
}

// goModFile returns the go.mod file of the module that contains dir, or "".
func goModFile(dir string) (string, error) {
	d, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	for {
		f := filepath.Join(d, "go.mod")
		if _, err := os.Stat(f); err == nil {
			return f, nil
		}
		parent := filepath.Dir(d)
		if parent == d {
			return "", nil
		}
		d = parent
	}
}

// typeCheckBlocks type checks the output with the code of the blocks and fixes
// or leaves out blocks until it type checks. It returns the output.
func typeCheckBlocks(dir, output, pkgName, hash, tags string, blocks []*block, pages []*goalPage, goalPaths map[string]string, goalRecord bool) ([]byte, error) {
	var src []byte
	for iter := 0; ; iter++ {
		src = assemble(pkgName, hash, blocks, pages)
		srcLines := strings.Split(string(src), "\n")
		if iter == 20 {
			return nil, fmt.Errorf("type checking did not converge")
		}
		errs, err := typeCheck(dir, output, src, tags)
		if err != nil {
			return nil, err
		}
		if len(errs) == 0 {
			break
		}
		changed := false
		failed := map[*block]bool{} // the blocks that fail in this iteration
		unused := map[*block]map[int][]string{}
		goalUnused := map[*goalPage]map[int][]string{}
		goalErr := map[*goalPage]int{} // first block with an error
		for _, e := range errs {
			if pg := goalPageAt(pages, e.line); pg != nil {
				if name, ok := strings.CutPrefix(e.msg, "declared and not used: "); ok {
					if goalUnused[pg] == nil {
						goalUnused[pg] = map[int][]string{}
					}
					goalUnused[pg][e.line-pg.start] = append(goalUnused[pg][e.line-pg.start], name)
					continue
				}
				i := pg.blockAtLine(e.line)
				if j, ok := goalErr[pg]; !ok || i < j {
					goalErr[pg] = i
					if pg.blocks[i].err == "" {
						pg.blocks[i].err = e.msg
					}
				}
				continue
			}
			b := blockAt(blocks, e.line)
			if b == nil {
				return nil, fmt.Errorf("error outside of the code blocks: %s", e)
			}
			if name, ok := strings.CutPrefix(e.msg, "declared and not used: "); ok {
				if unused[b] == nil {
					unused[b] = map[int][]string{}
				}
				unused[b][e.line-b.start] = append(unused[b][e.line-b.start], name)
				continue
			}
			if b.err == "" {
				b.err = e.msg
				failed[b] = true
				changed = true
			}
			if failed[b] {
				text := ""
				if e.line >= 1 && e.line <= len(srcLines) {
					text = srcLines[e.line-1]
				}
				line, col := b.markdownPos(e.line, e.col, text)
				b.errs = append(b.errs, blockError{line: line, col: col, msg: e.msg})
			}
		}
		for b, u := range unused {
			if b.err != "" || failed[b] {
				continue
			}
			if err := b.useUnused(u); err != nil {
				b.err = err.Error()
			}
			changed = true
		}
		for pg, i := range goalErr {
			pg.truncate(i, pg.blocks[i].err, goalPaths, goalRecord)
			changed = true
		}
		for pg, u := range goalUnused {
			if _, ok := goalErr[pg]; ok {
				continue
			}
			if err := pg.useUnused(u); err != nil {
				pg.truncate(0, err.Error(), goalPaths, goalRecord)
			}
			changed = true
		}
		if !changed {
			return nil, fmt.Errorf("could not fix the type errors: %v", errs)
		}
	}
	if f, err := format.Source(src); err == nil {
		src = f
	}
	return src, nil
}

// block is one code block, and the Go code generated for it.
type block struct {
	file   string // markdown file, relative to the package directory
	index  int    // number of the code block in the file, from 1
	line   int    // line of the code in the file
	src    string // source of the code block
	key    string // CodeKey of src
	name   string // name of the generated function
	code   string // generated Go declarations
	pkgs   map[string]bool
	indent int          // indentation of the code block in the file
	err    string       // why the block was left out
	errs   []blockError // the errors that left it out, in the file
	start  int          // first line of code in the output file
	end    int          // last line of code in the output file
}

// blockError is an error of a code block at a line (and column, if known)
// of its markdown file.
type blockError struct {
	line, col int
	msg       string
}

// stmtLine is the line of the generated code of a block that is a list of
// statements (from 0) at which its source code starts (see [block.generate]).
const stmtLine = 4

// markdownPos returns the line and column (0 if not known) in the markdown
// file of the given line and column of the output file, whose text is given.
// It finds the line of the code block whose text is that of the output line,
// apart from whitespace and the changes made in [block.generate], which is
// the closest to the line it would be at if the generated code had all of the
// lines of the code block in order, as it does for a list of statements apart
// from consecutive empty lines. It returns the first line of the code block
// if no line matches.
func (b *block) markdownPos(line, col int, text string) (int, int) {
	lines := strings.Split(b.src, "\n")
	hint := line - b.start - 1 - stmtLine
	norm := func(s string) string {
		s = strings.ReplaceAll(s, b.name+"_", "")
		s = strings.ReplaceAll(s, "("+outVar+", ", "(")
		s = strings.ReplaceAll(s, "("+outVar+")", "()")
		s = strings.ReplaceAll(s, "fmt.Fprint", "fmt.Print")
		s = strings.ReplaceAll(s, parentVar, "b")
		return strings.Join(strings.Fields(s), "")
	}
	want := norm(text)
	best := -1
	for i, l := range lines {
		if want == "" || norm(l) != want {
			continue
		}
		if best < 0 || abs(i-hint) < abs(best-hint) {
			best = i
		}
	}
	if best < 0 {
		return b.line, 0
	}
	// the column is known if the line is the same apart from indentation
	src := lines[best]
	tt, st := strings.TrimLeft(text, " \t"), strings.TrimLeft(src, " \t")
	if tt != st || col <= len(text)-len(tt) {
		return b.line + best, 0
	}
	return b.line + best, col - (len(text) - len(tt)) + (len(src) - len(st)) + b.indent
}

func abs(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

// displayPath returns the path of the given file, relative to dir, to show
// in messages: relative to the current directory if it is in it.
func displayPath(dir, file string) string {
	p := filepath.Join(dir, filepath.FromSlash(file))
	wd, err := os.Getwd()
	if err != nil {
		return p
	}
	ap, err := filepath.Abs(p)
	if err != nil {
		return p
	}
	if rel, err := filepath.Rel(wd, ap); err == nil && !strings.HasPrefix(rel, "..") {
		return rel
	}
	return ap
}

// pathName returns the package name of an import path (its last element).
func pathName(path string) string {
	return path[strings.LastIndex(path, "/")+1:]
}

// packageName returns the name of the package in dir.
func packageName(dir, tags string) (string, error) {
	args := []string{"list", "-f", "{{.Name}}"}
	if tags != "" {
		args = append(args, "-tags="+tags)
	}
	cmd := exec.Command("go", append(args, ".")...)
	cmd.Dir = dir
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go list: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

var fenceStart = regexp.MustCompile("^(\\s*)```Go\\s*$")

// readBlocks returns the ```Go code blocks of the markdown files in the
// content directory of the package in dir, once each (by key), in file order.
func readBlocks(dir, content string) ([]*block, error) {
	var blocks []*block
	seen := map[string]bool{}
	err := walkMarkdown(dir, content, func(rel string, lines []string) {
		forFences(lines, fenceStart, func(index, line, indent int, src string) {
			key := codeKey(src)
			if !seen[key] {
				seen[key] = true
				blocks = append(blocks, &block{file: rel, index: index, line: line, indent: indent, src: src, key: key})
			}
		})
	})
	return blocks, err
}

// walkMarkdown calls f with the path (relative to dir, with slashes) and
// the lines of each markdown file in the content directory of dir.
func walkMarkdown(dir, content string, f func(rel string, lines []string)) error {
	return filepath.WalkDir(filepath.Join(dir, content), func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".md" {
			return err
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		f(filepath.ToSlash(rel), strings.Split(string(b), "\n"))
		return nil
	})
}

// forFences calls f with the number (from 1, counting empty ones), line
// (from 1), indentation (in bytes) and source of each code block of the
// given lines that starts with a line matching start (whose first group is
// the indentation), in order, except empty ones.
func forFences(lines []string, start *regexp.Regexp, f func(index, line, indent int, src string)) {
	index := 0
	for i := 0; i < len(lines); i++ {
		m := start.FindStringSubmatch(lines[i])
		if m == nil {
			continue
		}
		index++
		indent := m[1]
		first := i + 1
		j := first
		for ; j < len(lines); j++ {
			if strings.HasPrefix(strings.TrimSpace(lines[j]), "```") {
				break
			}
		}
		code := make([]string, 0, j-first)
		for _, l := range lines[first:j] {
			code = append(code, strings.TrimPrefix(l, indent))
		}
		src := strings.Join(code, "\n") + "\n"
		if strings.TrimSpace(src) != "" {
			f(index, first+1, len(indent), src)
		}
		i = j
	}
}

// codeKey is [cogentcore.org/core/content.CodeKey].
func codeKey(src string) string {
	s := strings.Map(func(r rune) rune {
		if unicode.IsSpace(r) {
			return -1
		}
		return r
	}, src)
	h := uint32(2166136261) // FNV-1a
	for i := 0; i < len(s); i++ {
		h ^= uint32(s[i])
		h *= 16777619
	}
	return fmt.Sprintf("%08x-%d", h, len(s))
}

// generate makes the Go declarations of the block.
func (b *block) generate(importPaths map[string]string) error {
	b.pkgs = map[string]bool{}
	// a program has a main function (like mvmcore, which runs it); other code
	// is a list of statements, with the parent widget as b
	text := b.src
	if !strings.HasPrefix(strings.TrimSpace(text), "package ") {
		text = "package main\n\n" + text
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "block.go", text, parser.ParseComments)
	program := err == nil && file.Scope.Lookup("main") != nil
	if !program {
		// b is in an outer block, so that the code can declare its own b
		// (the source starts at line stmtLine of the function)
		text = "package main\n\nfunc " + b.name + "(" + parentVar + " *core.Frame, " + outVar + " io.Writer) {\nb := " + parentVar + "\n_ = b\n{\n" + b.src + "\n}\n}\n"
		fset = token.NewFileSet()
		file, err = parser.ParseFile(fset, "block.go", text, parser.ParseComments)
		if err != nil {
			var el scanner.ErrorList
			if errors.As(err, &el) && len(el) > 0 {
				for _, e := range el {
					// an error after the end of the code is at its last line
					i, col := e.Pos.Line-3-stmtLine, e.Pos.Column+b.indent
					if last := strings.Count(b.src, "\n") - 1; i > last {
						i, col = max(last, 0), 0
					}
					b.errs = append(b.errs, blockError{line: b.line + i, col: col, msg: e.Msg})
				}
				return errors.New(el[0].Msg)
			}
			return err
		}
	}
	local := map[string]string{}
	for _, im := range file.Imports {
		p, _ := strconv.Unquote(im.Path.Value)
		name := pathName(p)
		if im.Name != nil {
			name = im.Name.Name
		}
		local[name] = p
	}
	file.Imports = nil
	file.Decls = slices.DeleteFunc(file.Decls, func(d ast.Decl) bool {
		g, ok := d.(*ast.GenDecl)
		return ok && g.Tok == token.IMPORT
	})

	// identifiers that are not references: selectors and struct literal keys
	notRef := map[*ast.Ident]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.SelectorExpr:
			notRef[n.Sel] = true
		case *ast.KeyValueExpr:
			if id, ok := n.Key.(*ast.Ident); ok && id.Obj == nil {
				notRef[id] = true
			}
		}
		return true
	})
	top := map[*ast.Object]bool{}
	if program {
		for _, obj := range file.Scope.Objects {
			top[obj] = true
		}
	}
	// rewrite: package uses, fmt printing, top-level names, the parent b
	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.CallExpr:
			if sel, ok := n.Fun.(*ast.SelectorExpr); ok {
				if x, ok := sel.X.(*ast.Ident); ok && x.Obj == nil && x.Name == "fmt" {
					switch sel.Sel.Name {
					case "Print", "Println", "Printf":
						sel.Sel.Name = "Fp" + sel.Sel.Name[1:]
						n.Args = append([]ast.Expr{ast.NewIdent(outVar)}, n.Args...)
						b.pkgs["io"] = true
					}
				}
			}
		case *ast.SelectorExpr:
			if x, ok := n.X.(*ast.Ident); ok && x.Obj == nil {
				if p, ok := local[x.Name]; ok {
					b.pkgs[p] = true
				} else if p, ok := importPaths[x.Name]; ok {
					b.pkgs[p] = true
				}
			}
		case *ast.Ident:
			if notRef[n] {
				break
			}
			if n.Obj != nil && top[n.Obj] {
				n.Name = b.name + "_" + n.Name
			} else if program && n.Obj == nil && n.Name == "b" {
				n.Name = parentVar
			}
		}
		return true
	})
	if !program {
		b.pkgs["cogentcore.org/core/core"] = true
		b.pkgs["io"] = true
	}
	var buf bytes.Buffer
	for _, d := range file.Decls {
		if err := printer.Fprint(&buf, fset, &printer.CommentedNode{Node: d, Comments: file.Comments}); err != nil {
			return err
		}
		buf.WriteString("\n\n")
	}
	if program {
		fmt.Fprintf(&buf, "func %s(b *core.Frame, out io.Writer) {\n\t%s, %s = b, out\n\t%s_main()\n}\n\n", b.name, parentVar, outVar, b.name)
		b.pkgs["cogentcore.org/core/core"] = true
		b.pkgs["io"] = true
	}
	code, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	b.code = string(code)
	return nil
}

// useUnused inserts `_ = x` after the statements that declare the unused
// variables x of the block, given by the line of the error (relative to the
// start of the block's code: 1 is its first line).
func (b *block) useUnused(unused map[int][]string) error {
	code, err := useUnusedIn(b.code, unused)
	if err != nil {
		return err
	}
	b.code = code
	return nil
}

// useUnusedIn returns the given Go declarations with `_ = x` inserted
// after the statements that declare the unused variables x, given by the
// line of the error (1 is the first line of code).
func useUnusedIn(code string, unused map[int][]string) (string, error) {
	text := "package main\n" + code
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "block.go", text, parser.ParseComments)
	if err != nil {
		return "", err
	}
	ast.Inspect(file, func(n ast.Node) bool {
		blk, ok := n.(*ast.BlockStmt)
		if !ok {
			return true
		}
		var list []ast.Stmt
		for _, st := range blk.List {
			list = append(list, st)
			rel := fset.Position(st.Pos()).Line - 1
			for _, name := range unused[rel] {
				list = append(list, &ast.AssignStmt{Lhs: []ast.Expr{ast.NewIdent("_")}, Tok: token.ASSIGN, Rhs: []ast.Expr{ast.NewIdent(name)}})
			}
		}
		blk.List = list
		return true
	})
	var buf bytes.Buffer
	for _, d := range file.Decls {
		if err := printer.Fprint(&buf, fset, &printer.CommentedNode{Node: d, Comments: file.Comments}); err != nil {
			return "", err
		}
		buf.WriteString("\n\n")
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return "", err
	}
	return string(out), nil
}

// assemble returns the output file of the blocks that are not left out,
// and sets their line ranges. The comments name a block by its file and its
// number in the file, not its line, so that the output does not change (and
// is not generated again) when only the text around the code changes.
func assemble(pkgName, hash string, blocks []*block, pages []*goalPage) []byte {
	pkgs := map[string]bool{"cogentcore.org/core/content": true, "cogentcore.org/core/core": true, "io": true}
	for _, b := range blocks {
		if b.err != "" {
			continue
		}
		for p := range b.pkgs {
			pkgs[p] = true
		}
	}
	for _, pg := range pages {
		if pg.n == 0 {
			continue
		}
		for p := range pg.pkgs {
			pkgs[p] = true
		}
	}
	paths := make([]string, 0, len(pkgs))
	for p := range pkgs {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var buf bytes.Buffer
	buf.WriteString(header + hashPrefix + hash + "\n\n")
	fmt.Fprintf(&buf, "package %s\n\nimport (\n", pkgName)
	for _, p := range paths {
		fmt.Fprintf(&buf, "\t%q\n", p)
	}
	buf.WriteString(")\n\n")
	fmt.Fprintf(&buf, "// %s and %s are the parent widget (b) and output of the\n// code block programs that are running.\nvar (\n\t%s *core.Frame\n\t%s io.Writer\n)\n\n", parentVar, outVar, parentVar, outVar)
	buf.WriteString("// The code blocks are named by their markdown file and their number in it\n// (#n is the nth code block of its language in the file).\n")
	// an init function, not a blank variable: GoScript runs the var
	// initializers of a file of package main only if the main file imports it
	fmt.Fprintf(&buf, "func init() {\n\tcontent.AddCompiledCode(map[string]content.CodeFunc{\n")
	for _, b := range blocks {
		if b.err == "" {
			fmt.Fprintf(&buf, "\t\t%q: %s, // %s #%d\n", b.key, b.name, b.file, b.index)
		}
	}
	buf.WriteString("\t})\n")
	if slices.ContainsFunc(pages, func(pg *goalPage) bool { return pg.n > 0 }) {
		buf.WriteString("\tcontent.AddCompiledGoal(map[string]*content.GoalPage{\n")
		for _, pg := range pages {
			if pg.n == 0 {
				continue
			}
			fmt.Fprintf(&buf, "\t\t%q: {Start: %s, Keys: []string{", pg.key, pg.name)
			for i, b := range pg.blocks[:pg.n] {
				if i > 0 {
					buf.WriteString(", ")
				}
				fmt.Fprintf(&buf, "%q", b.key)
			}
			buf.WriteString("}},\n")
		}
		buf.WriteString("\t})\n")
	}
	buf.WriteString("}\n\n")
	line := bytes.Count(buf.Bytes(), []byte("\n")) + 1
	for _, b := range blocks {
		b.start, b.end = 0, 0
		if b.err != "" {
			continue
		}
		b.start = line
		fmt.Fprintf(&buf, "// %s #%d\n", b.file, b.index)
		buf.WriteString(b.code)
		buf.WriteString("\n")
		line += 1 + strings.Count(b.code, "\n") + 1
		b.end = line - 1
	}
	for _, pg := range pages {
		pg.start, pg.end = 0, 0
		if pg.n == 0 {
			continue
		}
		pg.start = line
		fmt.Fprintf(&buf, "// %s\n", pg.file)
		buf.WriteString(pg.code)
		buf.WriteString("\n")
		line += 1 + strings.Count(pg.code, "\n") + 1
		pg.end = line - 1
	}
	var left []string
	for _, pg := range pages {
		if pg.n < len(pg.blocks) {
			b := pg.blocks[pg.n]
			left = append(left, fmt.Sprintf("//   %s #%d: Goal code from here on (%d blocks): %s", pg.file, b.index, len(pg.blocks)-pg.n, strings.ReplaceAll(b.err, "\n", " ")))
		}
	}
	for _, b := range blocks {
		if b.err != "" {
			left = append(left, fmt.Sprintf("//   %s #%d: %s", b.file, b.index, strings.ReplaceAll(b.err, "\n", " ")))
		}
	}
	if len(left) > 0 {
		buf.WriteString("// Code blocks left out:\n" + strings.Join(left, "\n") + "\n")
	}
	return buf.Bytes()
}

// typeError is a type error at a line of the output file.
type typeError struct {
	line, col int
	msg       string
}

func (e typeError) String() string { return fmt.Sprintf("%d: %s", e.line, e.msg) }

// typeCheck type checks the package in dir with src as the output file,
// by building it with all errors reported.
func typeCheck(dir, output string, src []byte, tags string) ([]typeError, error) {
	if err := os.WriteFile(output, src, 0666); err != nil {
		return nil, err
	}
	args := []string{"build", "-o", os.DevNull, "-gcflags=-e"}
	if tags != "" {
		args = append(args, "-tags="+tags)
	}
	cmd := exec.Command("go", append(args, ".")...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err == nil {
		return nil, nil
	}
	base := filepath.Base(output)
	var errs []typeError
	var outside []string // the errors of the other files of the package
	for _, l := range strings.Split(string(out), "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		file, rest, _ := strings.Cut(l, ":")
		if filepath.Base(file) != base {
			if strings.HasSuffix(file, ".go") && !filepath.IsAbs(file) {
				l = displayPath(dir, file) + ":" + rest
			}
			outside = append(outside, l)
			continue
		}
		ls, rest, _ := strings.Cut(rest, ":")
		cs, msg, _ := strings.Cut(rest, ": ")
		line, _ := strconv.Atoi(ls)
		col, _ := strconv.Atoi(cs)
		errs = append(errs, typeError{line: line, col: col, msg: msg})
	}
	if len(outside) > 0 {
		return nil, fmt.Errorf("the code blocks can not be compiled, since the package of the app does not compile; fix these errors first:\n%s", strings.Join(outside, "\n"))
	}
	if len(errs) == 0 {
		return nil, fmt.Errorf("go build: %v: %s", err, out)
	}
	return errs, nil
}

// goalPageAt returns the Goal page at the given line of the output file.
func goalPageAt(pages []*goalPage, line int) *goalPage {
	for _, pg := range pages {
		if pg.start > 0 && line >= pg.start && line <= pg.end {
			return pg
		}
	}
	return nil
}

// blockAt returns the block at the given line of the output file.
func blockAt(blocks []*block, line int) *block {
	for _, b := range blocks {
		if b.start > 0 && line >= b.start && line <= b.end {
			return b
		}
	}
	return nil
}
