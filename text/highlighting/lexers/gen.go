//go:build ignore

// gen copies the XML lexer definitions of the included chroma lexers, and
// those of the lexers that they use, from the chroma module in the go.mod
// into this directory, and writes lexers.go with a function for each of
// them, and lexers_gen_test.go listing the functions.
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode"
)

// included are the XML files of the lexers that have a function, which are
// only those that Cogent Core apps use, until chroma provides individual
// lexers itself (https://github.com/alecthomas/chroma/issues/1414).
// go_template.xml is also copied for the Go lexer, written by hand in go.go.
var included = []string{
	"bash.xml",
	"toml.xml",
	"xml.xml",
}

// lexer is an XML lexer definition.
type lexer struct {
	file    string   // the name of the XML file
	name    string   // the name in its config
	aliases []string // the aliases in its config
	uses    []string // the names of the lexers that it uses
	fun     string   // the name of its function
	deps    []*lexer // the lexers that it uses, transitively
}

// config is the config element of an XML lexer definition.
type config struct {
	Name    string   `xml:"config>name"`
	Aliases []string `xml:"config>alias"`
}

var usingRe = regexp.MustCompile(`<using lexer="([^"]*)"`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/alecthomas/chroma/v3").Output()
	check(err)
	dir := filepath.Join(strings.TrimSpace(string(out)), "lexers", "embedded")
	files, err := filepath.Glob(filepath.Join(dir, "*.xml"))
	check(err)
	old, err := filepath.Glob("*.xml")
	check(err)
	for _, f := range old {
		check(os.Remove(f))
	}

	// Read the definitions, copying go_template.xml for go.go.
	byName := map[string]*lexer{}
	byFile := map[string]*lexer{}
	data := map[string][]byte{}
	for _, f := range files {
		b, err := os.ReadFile(f)
		check(err)
		base := filepath.Base(f)
		if base == "go_template.xml" {
			check(os.WriteFile(base, b, 0666))
		}
		data[base] = b
		var cfg config
		check(xml.Unmarshal(b, &cfg))
		lx := &lexer{file: base, name: cfg.Name, aliases: cfg.Aliases, fun: funcName(cfg.Name)}
		for _, m := range usingRe.FindAllStringSubmatch(string(b), -1) {
			if !slices.Contains(lx.uses, m[1]) {
				lx.uses = append(lx.uses, m[1])
			}
		}
		byFile[base] = lx
		for _, n := range append([]string{cfg.Name}, cfg.Aliases...) {
			byName[strings.ToLower(n)] = lx
		}
	}

	// Resolve the lexers that the included ones use, which are included too.
	var kept []*lexer
	for _, file := range included {
		lx := byFile[file]
		if !lx.resolve(byName, map[*lexer]bool{lx: true}) {
			panic(fmt.Sprintf("%s uses a lexer that is not in chroma", lx.name))
		}
		for _, l := range append([]*lexer{lx}, lx.deps...) {
			if slices.Contains(kept, l) {
				continue
			}
			if l != lx {
				l.resolve(byName, map[*lexer]bool{l: true})
			}
			kept = append(kept, l)
		}
	}
	slices.SortFunc(kept, func(a, b *lexer) int { return strings.Compare(a.fun, b.fun) })
	for _, lx := range kept {
		check(os.WriteFile(lx.file, data[lx.file], 0666))
	}
	writeLexers(kept)
	writeTest(kept)
}

// resolve sets the dependencies of the lexer, returning false if it uses a
// lexer that is not in byName. seen holds the lexers already included.
func (lx *lexer) resolve(byName map[string]*lexer, seen map[*lexer]bool) bool {
	var add func(l *lexer) bool
	add = func(l *lexer) bool {
		for _, u := range l.uses {
			d := byName[strings.ToLower(u)]
			if d == nil {
				return false
			}
			if seen[d] {
				continue
			}
			seen[d] = true
			lx.deps = append(lx.deps, d)
			if !add(d) {
				return false
			}
		}
		return true
	}
	return add(lx)
}

// funcName returns the exported Go name of the function for a lexer name.
func funcName(name string) string {
	name = strings.NewReplacer("++", "PP", "#", "Sharp", "'", "").Replace(name)
	var b strings.Builder
	upper := true
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	s := b.String()
	if !unicode.IsLetter(rune(s[0])) {
		s = "L" + s
	}
	return s
}

const header = `// Code generated by "go run gen.go"; DO NOT EDIT.

`

func writeLexers(lexers []*lexer) {
	var b bytes.Buffer
	b.WriteString(header + "package lexers\n\nimport (\n\t_ \"embed\"\n\n\t\"github.com/alecthomas/chroma/v3\"\n)\n")
	for _, lx := range lexers {
		fmt.Fprintf(&b, "\n//go:embed %s\nvar xml%s string\n", lx.file, lx.fun)
		fmt.Fprintf(&b, "\n// %s adds the chroma lexer for %s", lx.fun, lx.name)
		if len(lx.aliases) > 0 {
			fmt.Fprintf(&b, " (%s)", strings.Join(lx.aliases, ", "))
		}
		if len(lx.deps) > 0 {
			var names []string
			for _, d := range lx.deps {
				names = append(names, d.name)
			}
			fmt.Fprintf(&b, ",\n// and the lexers that it uses (%s),", strings.Join(names, ", "))
		}
		fmt.Fprintf(&b, "\n// to the registry.\nfunc %s(reg *chroma.LexerRegistry) {\n", lx.fun)
		for _, l := range append([]*lexer{lx}, lx.deps...) {
			fmt.Fprintf(&b, "\tregister(reg, %q, xml%s)\n", l.file, l.fun)
		}
		b.WriteString("}\n")
	}
	write("lexers.go", b.Bytes())
}

func writeTest(lexers []*lexer) {
	var b bytes.Buffer
	b.WriteString(header + "package lexers\n\nimport \"github.com/alecthomas/chroma/v3\"\n\n")
	b.WriteString("// all are the functions of the XML lexers, by the name of their lexer.\nvar all = map[string]func(reg *chroma.LexerRegistry){\n")
	for _, lx := range lexers {
		fmt.Fprintf(&b, "\t%q: %s,\n", lx.name, lx.fun)
	}
	b.WriteString("}\n")
	write("lexers_gen_test.go", b.Bytes())
}

func write(file string, b []byte) {
	src, err := format.Source(b)
	check(err)
	check(os.WriteFile(file, src, 0666))
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
